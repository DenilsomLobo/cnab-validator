# Define um texto para praticar a extração de campos por posição.
registro = "1234567890"

# Exibe os índices 0 a 2: o índice final 3 não entra no recorte.
print(registro[0:3])
# Exibe os índices 3 a 5, formando o texto 456.
print(registro[3:6])
# Exibe os índices 6 a 9, formando o texto 7890.
print(registro[6:10])
